-- CrescentLab PostgreSQL schema
-- Manual import only. Create the database yourself, then run:
--   psql -d crescentlab -f database/postgres/schema.sql
--
-- Rules:
-- - No physical foreign keys.
-- - No triggers.
-- - No custom functions.
-- - No views.
-- - No bootstrap data.
-- - No automatic migration assumptions.

-- =========================================================
-- 1. Users, groups, permissions, auth
-- =========================================================

CREATE TABLE user_groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL UNIQUE,
  description TEXT,
  is_admin BOOLEAN NOT NULL DEFAULT false,
  sort_order INTEGER NOT NULL DEFAULT 0,
  permissions_version BIGINT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at TIMESTAMPTZ,
  CHECK (code ~ '^[a-z][a-z0-9_]{1,62}$')
);

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id BIGINT,
  username TEXT NOT NULL,
  username_key TEXT NOT NULL UNIQUE,
  email TEXT,
  email_key TEXT UNIQUE,
  password_hash TEXT NOT NULL,
  nickname TEXT NOT NULL,
  avatar_file_id BIGINT,
  avatar_url TEXT,
  website TEXT,
  bio TEXT,
  status TEXT NOT NULL DEFAULT 'pending',
  is_system BOOLEAN NOT NULL DEFAULT false,
  email_verified_at TIMESTAMPTZ,
  activated_at TIMESTAMPTZ,
  last_login_at TIMESTAMPTZ,
  last_login_ip INET,
  password_changed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at TIMESTAMPTZ,
  CHECK (status IN ('pending', 'active', 'disabled', 'locked', 'deleted'))
);

CREATE TABLE permissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  module TEXT NOT NULL,
  action TEXT NOT NULL,
  description TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (code ~ '^[a-z][a-z0-9_.:-]{1,127}$')
);

CREATE TABLE user_group_permissions (
  group_id BIGINT NOT NULL,
  permission_id BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (group_id, permission_id)
);

CREATE TABLE user_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  session_hash TEXT NOT NULL UNIQUE,
  ip INET,
  user_agent TEXT,
  status TEXT NOT NULL DEFAULT 'active',
  last_seen_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (status IN ('active', 'expired', 'revoked'))
);

CREATE TABLE auth_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  token_hash TEXT NOT NULL UNIQUE,
  purpose TEXT NOT NULL,
  ip INET,
  user_agent TEXT,
  expires_at TIMESTAMPTZ NOT NULL,
  consumed_at TIMESTAMPTZ,
  revoked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (purpose IN ('refresh', 'email_activation', 'password_reset', 'email_change', 'api_key'))
);

CREATE TABLE audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT,
  action TEXT NOT NULL,
  target_type TEXT NOT NULL,
  target_id BIGINT,
  ip INET,
  user_agent TEXT,
  before_data JSONB,
  after_data JSONB,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================================================
-- 2. Storage, files, upload sessions
-- =========================================================

CREATE TABLE storage_policies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  type TEXT NOT NULL,
  bucket TEXT,
  endpoint TEXT,
  region TEXT,
  base_url TEXT,
  root_prefix TEXT NOT NULL DEFAULT '',
  public_read BOOLEAN NOT NULL DEFAULT false,
  force_path_style BOOLEAN NOT NULL DEFAULT false,
  is_default BOOLEAN NOT NULL DEFAULT false,
  config JSONB NOT NULL DEFAULT '{}'::jsonb,
  secrets_ciphertext JSONB NOT NULL DEFAULT '{}'::jsonb,
  status TEXT NOT NULL DEFAULT 'active',
  last_checked_at TIMESTAMPTZ,
  created_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at TIMESTAMPTZ,
  CHECK (type IN ('onedrive', 'aliyun_oss', 'aws_s3', 'cloudflare_r2', 's3_compatible', 'tencent_cos', 'qiniu')),
  CHECK (status IN ('active', 'disabled', 'error'))
);

CREATE TABLE storage_oauth_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  storage_policy_id BIGINT NOT NULL,
  provider TEXT NOT NULL,
  account_name TEXT,
  account_subject TEXT,
  token_ciphertext JSONB NOT NULL DEFAULT '{}'::jsonb,
  expires_at TIMESTAMPTZ,
  status TEXT NOT NULL DEFAULT 'active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (provider IN ('onedrive', 'custom')),
  CHECK (status IN ('active', 'expired', 'revoked', 'error'))
);

CREATE TABLE entities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sha256 CHAR(64) NOT NULL UNIQUE,
  size_bytes BIGINT NOT NULL DEFAULT 0,
  mime_type TEXT,
  ext TEXT,
  width INTEGER,
  height INTEGER,
  duration_seconds NUMERIC(12, 3),
  etag TEXT,
  ref_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (size_bytes >= 0),
  CHECK (ref_count >= 0)
);

CREATE TABLE files (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id BIGINT,
  owner_id BIGINT,
  storage_policy_id BIGINT,
  current_entity_id BIGINT,
  name TEXT NOT NULL,
  name_key TEXT NOT NULL,
  uri TEXT NOT NULL,
  type TEXT NOT NULL,
  mime_type TEXT,
  size_bytes BIGINT NOT NULL DEFAULT 0,
  is_public BOOLEAN NOT NULL DEFAULT false,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at TIMESTAMPTZ,
  CHECK (type IN ('file', 'folder')),
  CHECK (size_bytes >= 0)
);

CREATE TABLE file_entities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_id BIGINT NOT NULL,
  entity_id BIGINT NOT NULL,
  storage_policy_id BIGINT NOT NULL,
  object_key TEXT NOT NULL,
  version INTEGER NOT NULL DEFAULT 1,
  status TEXT NOT NULL DEFAULT 'available',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (file_id, version),
  UNIQUE (storage_policy_id, object_key),
  CHECK (version >= 1),
  CHECK (status IN ('uploading', 'available', 'missing', 'deleted'))
);

CREATE TABLE file_metadata (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_id BIGINT NOT NULL,
  key TEXT NOT NULL,
  value TEXT,
  value_json JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (file_id, key)
);

CREATE TABLE direct_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_id BIGINT NOT NULL,
  public_id TEXT NOT NULL UNIQUE,
  signed_token_hash TEXT,
  expires_at TIMESTAMPTZ,
  max_downloads INTEGER,
  download_count INTEGER NOT NULL DEFAULT 0,
  enabled BOOLEAN NOT NULL DEFAULT true,
  created_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (max_downloads IS NULL OR max_downloads > 0),
  CHECK (download_count >= 0)
);

CREATE TABLE upload_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_key TEXT NOT NULL UNIQUE,
  owner_id BIGINT,
  target_folder_id BIGINT,
  storage_policy_id BIGINT,
  completed_file_id BIGINT,
  filename TEXT NOT NULL,
  total_size_bytes BIGINT NOT NULL,
  chunk_size_bytes BIGINT NOT NULL,
  total_chunks INTEGER NOT NULL,
  received_chunks INTEGER NOT NULL DEFAULT 0,
  sha256 CHAR(64),
  status TEXT NOT NULL DEFAULT 'created',
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (status IN ('created', 'uploading', 'completed', 'failed', 'expired', 'cancelled')),
  CHECK (total_size_bytes >= 0),
  CHECK (chunk_size_bytes > 0),
  CHECK (total_chunks > 0),
  CHECK (received_chunks >= 0)
);

CREATE TABLE upload_chunks (
  session_id BIGINT NOT NULL,
  chunk_index INTEGER NOT NULL,
  size_bytes BIGINT NOT NULL,
  sha256 CHAR(64),
  object_key TEXT,
  received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (session_id, chunk_index),
  CHECK (chunk_index >= 0),
  CHECK (size_bytes >= 0)
);

CREATE TABLE file_thumbnails (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_id BIGINT NOT NULL,
  entity_id BIGINT,
  style_key TEXT NOT NULL,
  width INTEGER NOT NULL,
  height INTEGER NOT NULL,
  format TEXT NOT NULL DEFAULT 'webp',
  uri TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (file_id, style_key),
  CHECK (width > 0),
  CHECK (height > 0)
);


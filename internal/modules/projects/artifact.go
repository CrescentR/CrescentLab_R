const (
	maxArtifactUploadSize = 50 << 20
	maxArtifactFiles      = 1000
	maxArtifactExtracted  = 200 << 20
)

var allowedArtifactExtensions = map[string]bool{
	".html": true, ".htm": true, ".css": true, ".js": true, ".mjs": true,
	".json": true, ".map": true, ".xml": true, ".txt": true, ".webmanifest": true,
	".png": true, ".jpg": true, ".jpeg": true, ".gif": true, ".webp": true,
	".svg": true, ".ico": true, ".avif": true,
	".woff": true, ".woff2": true, ".ttf": true, ".otf": true,
	".wasm": true, ".pdf": true, ".mp4": true, ".webm": true,
	".mp3": true, ".ogg": true, ".wav": true,
}

type ProjectArtifact struct {
	ID          int64      `json:"id"`
	ProjectID   int64      `json:"project_id"`
	PublicID    string     `json:"public_id"`
	Version     int        `json:"version"`
	Label       string     `json:"label"`
	SourceType  string     `json:"source_type"`
	EntryPath   string     `json:"entry_path"`
	SizeBytes   int64      `json:"size_bytes"`
	SHA256      string     `json:"sha256"`
	IsPublished bool       `json:"is_published"`
	PublishedAt *time.Time `json:"published_at"`
	CreatedAt   time.Time  `json:"created_at"`
}

func (r *Repository) EnsureArtifactSchema(ctx context.Context) error {
	query := `CREATE TABLE IF NOT EXISTS project_artifacts (
		id INTEGER PRIMARY KEY AUTOINCREMENT,
		project_id INTEGER NOT NULL,
		public_id TEXT NOT NULL UNIQUE,
		version INTEGER NOT NULL,
		label TEXT NOT NULL DEFAULT '',
		source_type TEXT NOT NULL,
		entry_path TEXT NOT NULL DEFAULT 'index.html',
		storage_path TEXT NOT NULL,
		size_bytes INTEGER NOT NULL DEFAULT 0,
		sha256 TEXT NOT NULL,
		is_published BOOLEAN NOT NULL DEFAULT false,
		published_at DATETIME,
		created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
		UNIQUE(project_id, version)
	)`
	if r.driver == "postgres" {
		query = `CREATE TABLE IF NOT EXISTS project_artifacts (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			project_id BIGINT NOT NULL,
			public_id TEXT NOT NULL UNIQUE,
			version INTEGER NOT NULL,
			label TEXT NOT NULL DEFAULT '',
			source_type TEXT NOT NULL CHECK (source_type IN ('html', 'zip')),
			entry_path TEXT NOT NULL DEFAULT 'index.html',
			storage_path TEXT NOT NULL,
			size_bytes BIGINT NOT NULL DEFAULT 0,
			sha256 CHAR(64) NOT NULL,
			is_published BOOLEAN NOT NULL DEFAULT false,
			published_at TIMESTAMPTZ,
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
			UNIQUE(project_id, version)
		)`
	}
	if _, err := r.db.ExecContext(ctx, query); err != nil {
		return fmt.Errorf("create project artifacts schema: %w", err)
	}
	return nil
}

func (r *Repository) CreateArtifact(ctx context.Context, projectID int64, label, filename string, source io.Reader, root string) (ProjectArtifact, error) {
	if _, err := r.GetByID(ctx, projectID); err != nil {
		return ProjectArtifact{}, err
	}
	extension := strings.ToLower(filepath.Ext(filename))
	if extension != ".html" && extension != ".htm" && extension != ".zip" {
		return ProjectArtifact{}, errors.New("only HTML and ZIP artifacts are supported")
	}

	publicID := uuid.NewString()
	target := filepath.Join(root, publicID)
	if err := os.MkdirAll(target, 0o750); err != nil {
		return ProjectArtifact{}, fmt.Errorf("create artifact directory: %w", err)
	}
	cleanup := true
	defer func() {
		if cleanup {
			_ = os.RemoveAll(target)
		}
	}()

	temporary, err := os.CreateTemp(target, "upload-*")
	if err != nil {
		return ProjectArtifact{}, fmt.Errorf("create artifact upload: %w", err)
	}
	hash := sha256.New()
	size, copyErr := io.Copy(temporary, io.TeeReader(io.LimitReader(source, maxArtifactUploadSize+1), hash))
	closeErr := temporary.Close()
	if copyErr != nil || closeErr != nil {
		return ProjectArtifact{}, fmt.Errorf("write artifact upload: %w", errors.Join(copyErr, closeErr))
	}
	if size > maxArtifactUploadSize {
		return ProjectArtifact{}, errors.New("artifact exceeds the 50 MB upload limit")
	}

	sourceType := "html"
	if extension == ".zip" {
		sourceType = "zip"
		if err := extractArtifactZIP(temporary.Name(), target); err != nil {
			return ProjectArtifact{}, err
		}
	} else if err := os.Rename(temporary.Name(), filepath.Join(target, "index.html")); err != nil {
		return ProjectArtifact{}, fmt.Errorf("store HTML artifact: %w", err)
	}
	_ = os.Remove(temporary.Name())
	if _, err := os.Stat(filepath.Join(target, "index.html")); err != nil {
		return ProjectArtifact{}, errors.New("artifact must contain index.html at its root")
	}

	versionQuery := "SELECT COALESCE(MAX(version), 0) + 1 FROM project_artifacts WHERE project_id = ?"
	if r.driver == "postgres" {
		versionQuery = convertPlaceholders(versionQuery)
	}
	var version int
	if err := r.db.QueryRowContext(ctx, versionQuery, projectID).Scan(&version); err != nil {
		return ProjectArtifact{}, fmt.Errorf("allocate artifact version: %w", err)
	}

	digest := hex.EncodeToString(hash.Sum(nil))
	insert := "INSERT INTO project_artifacts (project_id, public_id, version, label, source_type, storage_path, size_bytes, sha256) VALUES (?, ?, ?, ?, ?, ?, ?, ?)"
	if r.driver == "postgres" {
		insert = convertPlaceholders(insert) + " RETURNING id"
	}
	var id int64
	args := []any{projectID, publicID, version, strings.TrimSpace(label), sourceType, target, size, digest}
	if r.driver == "postgres" {
		err = r.db.QueryRowContext(ctx, insert, args...).Scan(&id)
	} else {
		var result sql.Result
		result, err = r.db.ExecContext(ctx, insert, args...)
		if err == nil {
			id, err = result.LastInsertId()
		}
	}
	if err != nil {
		return ProjectArtifact{}, fmt.Errorf("create project artifact: %w", err)
	}
	cleanup = false
	return r.GetArtifact(ctx, id)
}

func (r *Repository) ListArtifacts(ctx context.Context, projectID int64) ([]ProjectArtifact, error) {
	query := "SELECT id, project_id, public_id, version, label, source_type, entry_path, size_bytes, sha256, is_published, published_at, created_at FROM project_artifacts WHERE project_id = ? ORDER BY version DESC"
	if r.driver == "postgres" {
		query = convertPlaceholders(query)
	}
	rows, err := r.db.QueryContext(ctx, query, projectID)
	if err != nil {
		return nil, fmt.Errorf("list project artifacts: %w", err)
	}
	defer rows.Close()
	items := make([]ProjectArtifact, 0)
	for rows.Next() {
		item, err := scanArtifact(rows)
		if err != nil {
			return nil, err
		}
		items = append(items, item)
	}
	return items, rows.Err()
}

func (r *Repository) GetArtifact(ctx context.Context, id int64) (ProjectArtifact, error) {
	query := "SELECT id, project_id, public_id, version, label, source_type, entry_path, size_bytes, sha256, is_published, published_at, created_at FROM project_artifacts WHERE id = ?"
	if r.driver == "postgres" {
		query = convertPlaceholders(query)
	}
	return scanArtifact(r.db.QueryRowContext(ctx, query, id))
}

func (r *Repository) PublishArtifact(ctx context.Context, projectID, artifactID int64) (ProjectArtifact, error) {
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return ProjectArtifact{}, err
	}
	defer tx.Rollback()
	clear := "UPDATE project_artifacts SET is_published = false, published_at = NULL WHERE project_id = ?"
	set := "UPDATE project_artifacts SET is_published = true, published_at = CURRENT_TIMESTAMP WHERE id = ? AND project_id = ?"
	if r.driver == "postgres" {
		clear, set = convertPlaceholders(clear), convertPlaceholders(set)
	}
	if _, err = tx.ExecContext(ctx, clear, projectID); err != nil {
		return ProjectArtifact{}, err
	}
	result, err := tx.ExecContext(ctx, set, artifactID, projectID)
	if err != nil {
		return ProjectArtifact{}, err
	}
	affected, _ := result.RowsAffected()
	if affected == 0 {
		return ProjectArtifact{}, sql.ErrNoRows
	}
	if err := tx.Commit(); err != nil {
		return ProjectArtifact{}, err
	}
	return r.GetArtifact(ctx, artifactID)
}

func (r *Repository) ArtifactFile(ctx context.Context, publicID, requestedPath string) (string, error) {
	var storagePath string
	query := "SELECT storage_path FROM project_artifacts WHERE public_id = ?"
	if r.driver == "postgres" {
		query = convertPlaceholders(query)
	}
	if err := r.db.QueryRowContext(ctx, query, publicID).Scan(&storagePath); err != nil {
		return "", err
	}
	clean := filepath.Clean(strings.TrimPrefix(requestedPath, "/"))
	if clean == "." {
		clean = "index.html"
	}
	if filepath.IsAbs(clean) || clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
		return "", errors.New("invalid artifact path")
	}
	fullPath := filepath.Join(storagePath, clean)
	relative, err := filepath.Rel(storagePath, fullPath)
	if err != nil || relative == ".." || strings.HasPrefix(relative, ".."+string(filepath.Separator)) {
		return "", errors.New("invalid artifact path")
	}
	info, err := os.Stat(fullPath)
	if err != nil || info.IsDir() {
		return "", sql.ErrNoRows
	}
	return fullPath, nil
}

func (r *Repository) PublishedArtifactFile(ctx context.Context, slug, requestedPath string) (string, error) {
	var publicID string
	query := `SELECT a.public_id
		FROM project_artifacts a
		JOIN projects p ON p.id = a.project_id
		WHERE p.slug = ? AND p.deleted_at IS NULL AND a.is_published = true`
	if r.driver == "postgres" {
		query = convertPlaceholders(query)
	}
	if err := r.db.QueryRowContext(ctx, query, slug).Scan(&publicID); err != nil {
		return "", err
	}
	return r.ArtifactFile(ctx, publicID, requestedPath)
}

func extractArtifactZIP(sourcePath, target string) error {
	reader, err := zip.OpenReader(sourcePath)
	if err != nil {
		return errors.New("invalid ZIP artifact")
	}
	defer reader.Close()
	if len(reader.File) > maxArtifactFiles {
		return errors.New("ZIP artifact contains too many files")
	}
	var extracted int64
	for _, file := range reader.File {
		clean := filepath.Clean(file.Name)
		if filepath.IsAbs(clean) || clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) || file.Mode()&os.ModeSymlink != 0 {
			return errors.New("ZIP artifact contains an unsafe path")
		}
		if file.FileInfo().IsDir() {
			continue
		}
		if !allowedArtifactExtensions[strings.ToLower(filepath.Ext(clean))] {
			return fmt.Errorf("ZIP artifact contains unsupported file type %q", filepath.Ext(clean))
		}
		extracted += int64(file.UncompressedSize64)
		if extracted > maxArtifactExtracted {
			return errors.New("ZIP artifact exceeds the 200 MB extracted limit")
		}
		destination := filepath.Join(target, clean)
		if err := os.MkdirAll(filepath.Dir(destination), 0o750); err != nil {
			return err
		}
		input, err := file.Open()
		if err != nil {
			return err
		}
		output, err := os.OpenFile(destination, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o640)
		if err != nil {
			input.Close()
			return err
		}
		_, copyErr := io.Copy(output, io.LimitReader(input, maxArtifactExtracted+1))
		closeErr := errors.Join(input.Close(), output.Close())
		if copyErr != nil || closeErr != nil {
			return errors.Join(copyErr, closeErr)
		}
	}
	return nil
}

type artifactScanner interface {
	Scan(...any) error
}

func scanArtifact(scanner artifactScanner) (ProjectArtifact, error) {
	var item ProjectArtifact
	var publishedAt sql.NullTime
	if err := scanner.Scan(&item.ID, &item.ProjectID, &item.PublicID, &item.Version, &item.Label, &item.SourceType, &item.EntryPath, &item.SizeBytes, &item.SHA256, &item.IsPublished, &publishedAt, &item.CreatedAt); err != nil {
		return ProjectArtifact{}, err
	}
	if publishedAt.Valid {
		item.PublishedAt = &publishedAt.Time
	}
	return item, nil
}

func artifactContentType(path string) string {
	if contentType := mime.TypeByExtension(strings.ToLower(filepath.Ext(path))); contentType != "" {
		return contentType
	}
	file, err := os.Open(path)
	if err != nil {
		return "application/octet-stream"
	}
	defer file.Close()
	sample := make([]byte, 512)
	count, _ := file.Read(sample)
	return http.DetectContentType(sample[:count])
}

package observatory

import (
	"context"
	"fmt"
)

func (r *Repository) EnsureSchema(ctx context.Context) error {
	if r == nil || r.db == nil {
		return fmt.Errorf("observatory repository database is nil")
	}
	if r.driver == "postgres" {
		_, err := r.db.ExecContext(ctx, `
CREATE TABLE IF NOT EXISTS observatory_notes (
  project_id BIGINT,
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id TEXT UNIQUE,
  title TEXT NOT NULL,
  content_md TEXT NOT NULL DEFAULT '',
  content_html TEXT NOT NULL DEFAULT '',
  question TEXT NOT NULL DEFAULT '',
  observation TEXT NOT NULL DEFAULT '',
  conclusion TEXT NOT NULL DEFAULT '',
  next_step TEXT NOT NULL DEFAULT '',
  tags JSONB NOT NULL DEFAULT '[]'::jsonb,
  note_type TEXT NOT NULL DEFAULT 'fragment',
  status TEXT NOT NULL DEFAULT 'active',
  visibility TEXT NOT NULL DEFAULT 'private',
  is_featured BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at TIMESTAMPTZ,
  CHECK (note_type IN ('fragment', 'failure', 'idea', 'tool_idea', 'tech_debt')),
  CHECK (status IN ('active', 'resolved', 'abandoned')),
  CHECK (visibility IN ('public', 'private'))
);
ALTER TABLE observatory_notes ADD COLUMN IF NOT EXISTS question TEXT NOT NULL DEFAULT '';
ALTER TABLE observatory_notes ADD COLUMN IF NOT EXISTS observation TEXT NOT NULL DEFAULT '';
ALTER TABLE observatory_notes ADD COLUMN IF NOT EXISTS conclusion TEXT NOT NULL DEFAULT '';
ALTER TABLE observatory_notes ADD COLUMN IF NOT EXISTS next_step TEXT NOT NULL DEFAULT '';
ALTER TABLE observatory_notes ADD COLUMN IF NOT EXISTS visibility TEXT NOT NULL DEFAULT 'private';
ALTER TABLE observatory_notes ADD COLUMN IF NOT EXISTS is_featured BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE observatory_notes DROP CONSTRAINT IF EXISTS observatory_notes_visibility_check;
ALTER TABLE observatory_notes ADD CONSTRAINT observatory_notes_visibility_check
  CHECK (visibility IN ('public', 'private'));`)
		if err != nil {
			return fmt.Errorf("ensure postgres observatory schema: %w", err)
		}
		return nil
	}
	if r.driver != "sqlite" {
		return fmt.Errorf("unsupported observatory database driver %q", r.driver)
	}
	_, err := r.db.ExecContext(ctx, `
CREATE TABLE IF NOT EXISTS observatory_notes (
  project_id BIGINT,
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  public_id TEXT UNIQUE,
  title TEXT NOT NULL,
  content_md TEXT NOT NULL DEFAULT '',
  content_html TEXT NOT NULL DEFAULT '',
  question TEXT NOT NULL DEFAULT '',
  observation TEXT NOT NULL DEFAULT '',
  conclusion TEXT NOT NULL DEFAULT '',
  next_step TEXT NOT NULL DEFAULT '',
  tags TEXT NOT NULL DEFAULT '[]',
  note_type TEXT NOT NULL DEFAULT 'fragment',
  status TEXT NOT NULL DEFAULT 'active',
  visibility TEXT NOT NULL DEFAULT 'private',
  is_featured INTEGER NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at DATETIME
);`)
	if err != nil {
		return fmt.Errorf("ensure sqlite observatory schema: %w", err)
	}
	alters := []string{
		`ALTER TABLE observatory_notes ADD COLUMN question TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE observatory_notes ADD COLUMN observation TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE observatory_notes ADD COLUMN conclusion TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE observatory_notes ADD COLUMN next_step TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE observatory_notes ADD COLUMN visibility TEXT NOT NULL DEFAULT 'private'`,
		`ALTER TABLE observatory_notes ADD COLUMN is_featured INTEGER NOT NULL DEFAULT 0`,
	}
	for _, query := range alters {
		_, _ = r.db.ExecContext(ctx, query)
	}
	return nil
}

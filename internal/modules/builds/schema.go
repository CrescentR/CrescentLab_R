package builds

import (
	"context"
	"fmt"
)

func (r *Repository) EnsureSchema(ctx context.Context) error {
	if r == nil || r.db == nil {
		return fmt.Errorf("builds repository database is nil")
	}
	if r.driver == "postgres" {
		_, err := r.db.ExecContext(ctx, `
CREATE TABLE IF NOT EXISTS builds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id TEXT UNIQUE,
  name TEXT NOT NULL,
  slug TEXT NOT NULL,
  one_liner TEXT NOT NULL DEFAULT '',
  stage TEXT NOT NULL DEFAULT 'prototype',
  round_goal TEXT NOT NULL DEFAULT '',
  latest_progress TEXT NOT NULL DEFAULT '',
  next_step TEXT NOT NULL DEFAULT '',
  detail_url TEXT,
  demo_url TEXT,
  repo_url TEXT,
  status TEXT NOT NULL DEFAULT 'draft',
  sort_order INTEGER NOT NULL DEFAULT 0,
  progressed_at TIMESTAMPTZ,
  published_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at TIMESTAMPTZ,
  CHECK (stage IN ('prototype', 'development', 'validating', 'beta', 'paused')),
  CHECK (status IN ('draft', 'published', 'archived'))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_builds_slug_active ON builds (slug) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_builds_home ON builds (status, sort_order, progressed_at DESC) WHERE deleted_at IS NULL;`)
		if err != nil {
			return fmt.Errorf("ensure postgres builds schema: %w", err)
		}
		return nil
	}
	if r.driver != "sqlite" {
		return fmt.Errorf("unsupported builds database driver %q", r.driver)
	}
	_, err := r.db.ExecContext(ctx, `
CREATE TABLE IF NOT EXISTS builds (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  public_id TEXT UNIQUE,
  name TEXT NOT NULL,
  slug TEXT NOT NULL,
  one_liner TEXT NOT NULL DEFAULT '',
  stage TEXT NOT NULL DEFAULT 'prototype',
  round_goal TEXT NOT NULL DEFAULT '',
  latest_progress TEXT NOT NULL DEFAULT '',
  next_step TEXT NOT NULL DEFAULT '',
  detail_url TEXT,
  demo_url TEXT,
  repo_url TEXT,
  status TEXT NOT NULL DEFAULT 'draft',
  sort_order INTEGER NOT NULL DEFAULT 0,
  progressed_at DATETIME,
  published_at DATETIME,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at DATETIME,
  CHECK (stage IN ('prototype', 'development', 'validating', 'beta', 'paused')),
  CHECK (status IN ('draft', 'published', 'archived'))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_builds_slug_active ON builds (slug) WHERE deleted_at IS NULL;`)
	if err != nil {
		return fmt.Errorf("ensure sqlite builds schema: %w", err)
	}
	return nil
}
